// ============ حل ریاضی ساده ============

function solveMath(text) {
  // تبدیل اعداد فارسی به انگلیسی
  const persianDigits = '۰۱۲۳۴۵۶۷۸۹'
  const englishDigits = '0123456789'

  let normalized = text
  for (let i = 0; i < 10; i++) {
    normalized = normalized.replace(new RegExp(persianDigits[i], 'g'), englishDigits[i])
  }

  // جایگزینی علامت‌ها
  normalized = normalized
    .replace(/×/g, '*')
    .replace(/÷/g, '/')
    .replace(/\+/g, '+')
    .replace(/−/g, '-')
    .replace(/[٠-٩]/g, (d) => '٠١٢٣٤٥٦٧٨٩'.indexOf(d))

  // پیدا کردن عبارت ریاضی
  const mathRegex = /(\d+(?:\.\d+)?)\s*([+\-*/])\s*(\d+(?:\.\d+)?)/
  const match = normalized.match(mathRegex)

  if (match) {
    const a = parseFloat(match[1])
    const op = match[2]
    const b = parseFloat(match[3])

    let result
    switch (op) {
      case '+': result = a + b; break
      case '-': result = a - b; break
      case '*': result = a * b; break
      case '/': result = b !== 0 ? a / b : null; break
      default: return null
    }

    if (result !== null) {
      // گرد کردن
      const rounded = Number.isInteger(result) ? result : result.toFixed(2)
      return `${a} ${op} ${b} = ${rounded} ✅`
    }
  }

  return null
}

// ============ تحلیل ریاضی + توضیح ============

function explainMath(text) {
  const persianDigits = '۰۱۲۳۴۵۶۷۸۹'
  let normalized = text
  for (let i = 0; i < 10; i++) {
    normalized = normalized.replace(new RegExp(persianDigits[i], 'g'), i)
  }

  // ضرب
  const multiply = normalized.match(/(\d+)\s*[*×x]\s*(\d+)/)
  if (multiply) {
    const a = parseInt(multiply[1])
    const b = parseInt(multiply[2])
    const result = a * b

    // تقسیم به دهگان و یکان
    const tens = Math.floor(a / 10) * 10
    const ones = a % 10

    if (tens > 0 && ones > 0) {
      return `🧮 بیا با هم حلش کنیم:\n\n${a} × ${b}\n\nمرحله ۱: عدد ${a} رو به دو تیکه تقسیم کن:\n${tens} + ${ones}\n\nمرحله ۲: هر کدوم رو جدا در ${b} ضرب کن:\n${tens} × ${b} = ${tens * b}\n${ones} × ${b} = ${ones * b}\n\nمرحله ۳: جواب‌ها رو جمع کن:\n${tens * b} + ${ones * b} = ${result}\n\n✅ پس ${a} × ${b} = ${result}\n\nالان خودت یه بار دیگه امتحان کن! 💪`
    }

    return `🧮 راهنمایی:\n\n${a} × ${b} = ؟\n\n💡 یه راه ساده:\n${a} رو ${b} بار با خودش جمع کن\n\nمثلاً اگه ${a} = ۵ و ${b} = ۳:\n۵+۵+۵ = ۱۵\n\nالان خودت امتحان کن! 🎯`
  }

  return null
}

